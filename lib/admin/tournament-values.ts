import type { Tournament } from "../db/schema";
import { toDateTimeLocalValue } from "../format";
import type { TournamentFormValues } from "@/components/admin/TournamentForm";

const money = (c: number | null) => (c == null ? "" : String(c / 100));
const num = (n: number | null) => (n == null ? "" : String(n));

export function tournamentToForm(t: Tournament): TournamentFormValues {
  return {
    id: t.id,
    name: t.name,
    description: t.description,
    gameVariant: t.gameVariant,
    format: t.format,
    startsAt: toDateTimeLocalValue(t.startsAt),
    endsAt: toDateTimeLocalValue(t.endsAt),
    registrationOpensAt: toDateTimeLocalValue(t.registrationOpensAt),
    registrationClosesAt: toDateTimeLocalValue(t.registrationClosesAt),
    registrationMode: t.registrationMode,
    currency: t.currency,
    buyIn: money(t.buyInCents),
    fee: money(t.feeCents),
    guarantee: money(t.guaranteeCents),
    bounty: money(t.bountyCents),
    reentryCount: num(t.reentryCount),
    externalBookingUrl: t.externalBookingUrl ?? "",
    reentryPrice: money(t.reentryPriceCents),
    reentryFee: money(t.reentryFeeCents),
    levels: t.levels,
    startingStack: num(t.startingStack),
    blindLevelMinutes: num(t.blindLevelMinutes),
    blindStructure: t.blindStructure,
    lateRegistration: t.lateRegistration,
    reentryPolicy: t.reentryPolicy,
    rules: t.rules,
    venue: t.venue,
    coverImageUrl: t.coverImageUrl ?? "",
    tableCount: String(t.tableCount),
    seatsPerTable: String(t.seatsPerTable),
    tableLabels: t.tableLabels.join("\n"),
    capacity: String(t.capacity),
    maxPlacesPerBooking: String(t.maxPlacesPerBooking),
    seatSelection: t.seatSelection,
    waitlistEnabled: t.waitlistEnabled,
    featured: t.featured,
    status: t.status,
  };
}

